r"""Reconstruct the simulation study of Wilson (2026), section 7.

The paper's tables were generated by a script that is not public. This
module rebuilds the study from the paper's text, using only the public
API of :mod:`trickle_down`. Where the text leaves a detail unstated, the
module fixes it to a documented assumption; :data:`ASSUMPTIONS` lists
every one, and the docs print that list beside the results.

The study has three parts.

- A worked example (section 7.1): one population of 10,000, a T-learner
  and a depth-three tree fit on the training half, and the interweaved
  hierarchy tested on the evaluation half.
- Familywise error rate (section 7.2): 4,000 populations of 4,000 under
  the global null, each tested over a partition fixed in advance and over
  a fitted tree, so the two columns are paired.
- Power (section 7.3): the fixed partition under two effect
  configurations, scaled by a factor, counting the true claims each of
  five procedures certifies.

References
----------
Wilson, B. (2026). Interpretable and validatable uplift modeling.
arXiv:2610.37966.

"""

from __future__ import annotations

