Cell = tuple[int, int]
ALL_CELLS: frozenset[Cell] = frozenset({(0, 0), (0, 1), (1, 0), (1, 1)})


@dataclass(frozen=True)
class EffectConfiguration:
    """Treatment effect in each (x2, x3) cell."""

    name: str
    tau: Mapping[Cell, float]

    def scaled(self, scale: float) -> EffectConfiguration:
        """Multiply every cell's effect by ``scale``."""
        return EffectConfiguration(
            name=self.name,
            tau={cell: scale * value for cell, value in self.tau.items()},
        )

    def average(self, cells: frozenset[Cell]) -> float:
        """Average effect over a union of cells.

        The cells are equally likely and independent of every other
        feature, so a node's true effect depends only on which cells it
        admits, whatever other splits define it.
        """
        if len(cells) == 0:
            raise ValueError("A node must admit at least one cell.")

        return sum(self.tau[cell] for cell in cells) / len(cells)

    def individual_effects(
        self, x2: npt.NDArray[np.int64], x3: npt.NDArray[np.int64]
    ) -> npt.NDArray[np.float64]:
        """Each individual's effect, looked up from their cell."""
        tau = np.empty(x2.shape[0], dtype=np.float64)
        for (a, b), value in self.tau.items():
            tau[(x2 == a) & (x3 == b)] = value

        return tau


RUNNING_EXAMPLE = EffectConfiguration(
    name="The running example: one quarter harmed",
    tau={(0, 0): -1.00, (0, 1): 1.20, (1, 0): 2.00, (1, 1): 1.50},
)
EVERY_SUBGROUP_HELPED = EffectConfiguration(
    name="Every subgroup helped",
    tau={(0, 0): 0.30, (0, 1): 1.20, (1, 0): 2.00, (1, 1): 1.50},
)
GLOBAL_NULL = EffectConfiguration(
    name="Global null",
    tau=dict.fromkeys(ALL_CELLS, 0.0),
)


@dataclass(frozen=True)
class Sample:
    """Features, treatment indicators and observed outcomes."""

    X: npt.NDArray[np.float64]  # shape (n, 10)
    z: npt.NDArray[np.bool_]  # shape (n,)
    y: npt.NDArray[np.float64]  # shape (n,)

    @property
    def size(self) -> int:
        """Number of individuals."""
        return int(self.y.shape[0])

    def subset(self, index: npt.NDArray[np.int64]) -> Sample:
        """The individuals at ``index``."""
        return Sample(X=self.X[index], z=self.z[index], y=self.y[index])


def generate_population(
    rng: np.random.Generator,
    n: int,
    effects: EffectConfiguration,
    effect_noise_sd: float = EFFECT_NOISE_SD,
) -> Sample:
    r"""Draw ``n`` individuals and reveal one potential outcome each.

    The baseline outcome is :math:`Y(0) = x_0 + 0.3 x_1 + \varepsilon_0`
    with :math:`\varepsilon_0 \sim N(0, 9)`, and
    :math:`Y(1) = Y(0) + \tau(x) + \varepsilon_1` (paper, section 7.1).
    """
    x0 = rng.standard_normal(n)
    x1 = rng.integers(0, 3, size=n)
    x2 = rng.integers(0, 2, size=n)
    x3 = rng.integers(0, 2, size=n)
    noise = rng.standard_normal((n, 6))  # x4, ..., x9
    X = np.column_stack([x0, x1, x2, x3, noise]).astype(np.float64)

    y0 = x0 + 0.3 * x1 + rng.normal(0.0, OUTCOME_NOISE_SD, size=n)
    y1 = (
        y0
        + effects.individual_effects(x2, x3)
        + rng.normal(0.0, effect_noise_sd, size=n)
    )
    z = rng.random(n) < 0.5

    return Sample(X=X, z=z, y=np.where(z, y1, y0))


def split_halves(rng: np.random.Generator, sample: Sample) -> tuple[Sample, Sample]:
    """Split uniformly at random into training and evaluation halves."""
    index = rng.permutation(sample.size)
    half = sample.size // 2
    return sample.subset(index[:half]), sample.subset(index[half:])


@dataclass(frozen=True)
class Condition:
    """One side of one split: ``x_feature > threshold`` or its negation."""

    feature: int
    threshold: float
    above: bool

    def mask(self, X: npt.NDArray[np.float64]) -> npt.NDArray[np.bool_]:
        """Which rows satisfy the condition."""
        column = X[:, self.feature]
        if self.above:
            return np.asarray(column > self.threshold)

        return np.asarray(column <= self.threshold)

    def label(self) -> str:
        """Human-readable form, as in the paper's Figure 2."""
        if self.feature in MODERATORS and 0.0 < self.threshold < 1.0:
            return f"x{self.feature} = {1 if self.above else 0}"

        sign = ">" if self.above else "<="
        return f"x{self.feature} {sign} {self.threshold:.3g}"

    def admits(self, cell: Cell) -> bool:
        """Whether individuals in ``cell`` can satisfy the condition."""
        if self.feature not in MODERATORS:
            return True

        value = cell[MODERATORS.index(self.feature)]
        return (value > self.threshold) == self.above


@dataclass
class Region:
    """A node of a partition: the conditions on the path to it."""

    conditions: tuple[Condition, ...] = ()
    children: list[Region] = field(default_factory=list)

    @property
    def name(self) -> str:
        """The path from the root, which keeps names unique."""
        if len(self.conditions) == 0:
            return "everyone"

        return ", ".join(condition.label() for condition in self.conditions)

    @property
    def cells(self) -> frozenset[Cell]:
        """The (x2, x3) cells this region admits."""
        return frozenset(
            cell
            for cell in ALL_CELLS
            if all(condition.admits(cell) for condition in self.conditions)
        )

    def mask(self, X: npt.NDArray[np.float64]) -> npt.NDArray[np.bool_]:
        """Which rows fall in the region."""
        mask = np.ones(X.shape[0], dtype=bool)
        for condition in self.conditions:
            mask &= condition.mask(X)

        return mask

    def split(self, feature: int, threshold: float) -> Region:
        """Give the region two children, split at ``threshold``."""
        self.children = [
            Region((*self.conditions, Condition(feature, threshold, False))),
            Region((*self.conditions, Condition(feature, threshold, True))),
        ]
        return self

    def walk(self) -> list[Region]:
        """Every region at or below this one, parents before children."""
        ordered: list[Region] = []
        queue: list[Region] = [self]
        while queue:
            region = queue.pop(0)
            ordered.append(region)
            queue.extend(region.children)

        return ordered


def fixed_partition() -> Region:
    """Split on x2, then on x3 within each half: the true structure."""
    root = Region().split(2, 0.5)
    for child in root.children:
        child.split(3, 0.5)

    return root


def fit_t_learner_effects(
    train: Sample, random_state: int = 0
) -> npt.NDArray[np.float64]:
    r"""Individual effect estimates on the training half (section 7.1).

    Fits :math:`\hat{\mu}_0` and :math:`\hat{\mu}_1` on the two arms and
    returns :math:`\hat{\mu}_1(x) - y` for controls and
    :math:`y - \hat{\mu}_0(x)` for the treated.
    """
    models = []
    for arm in (False, True):
        model = HistGradientBoostingRegressor(
            max_iter=200,
            max_depth=4,
            learning_rate=0.1,
            random_state=random_state,
        )
        model.fit(train.X[train.z == arm], train.y[train.z == arm])
        models.append(model)

    mu0, mu1 = models
    return np.where(
        train.z,
        train.y - mu0.predict(train.X),
        mu1.predict(train.X) - train.y,
    )


def fitted_partition(
    train: Sample,
    max_depth: int = 3,
    min_leaf_fraction: float = 0.01,
    random_state: int = 0,
) -> Region:
    """Distil a T-learner into a shallow regression tree on the training half."""
    effects = fit_t_learner_effects(train, random_state=random_state)
    tree = DecisionTreeRegressor(
        max_depth=max_depth,
        min_samples_leaf=min_leaf_fraction,
        random_state=random_state,
    )
    tree.fit(train.X, effects)
    structure = tree.tree_

    def grow(region: Region, node: int) -> None:
        left = int(structure.children_left[node])
        if left == -1:
            return

        region.split(int(structure.feature[node]), float(structure.threshold[node]))
        grow(region.children[0], left)
        grow(region.children[1], int(structure.children_right[node]))

    root = Region()
    grow(root, 0)
    return root


def to_uplift_tree(
    region: Region, train: Sample, evaluation: Sample
) -> UpliftNode | None:
    """Summarize each region's arms: moments on evaluation, tau on training.

    Returns None when the region itself cannot be tested. A split either
    of whose children cannot be tested is dropped, so the region becomes
    a leaf.
    """
    in_train = region.mask(train.X)
    in_eval = region.mask(evaluation.X)

    treated_train = train.y[in_train & train.z]
    control_train = train.y[in_train & ~train.z]
    treated_eval = evaluation.y[in_eval & evaluation.z]
    control_eval = evaluation.y[in_eval & ~evaluation.z]
    if min(treated_train.size, control_train.size) < 1:
        return None

    if min(treated_eval.size, control_eval.size) < 2:
        return None

    children: list[UpliftNode] = []
    if len(region.children) == 2:
        built = [to_uplift_tree(child, train, evaluation) for child in region.children]
        if built[0] is not None and built[1] is not None:
            children = [built[0], built[1]]

    return UpliftNode(
        name=region.name,
        treated=ArmSummary.from_samples(treated_eval),
        control=ArmSummary.from_samples(control_eval),
        tau_train=float(np.mean(treated_train) - np.mean(control_train)),
        children=children,
    )


def null_is_true(estimand: float, delta: float, alternative: str) -> bool:
    """Whether the null tested under ``alternative`` holds.

    "greater" tests ``estimand <= delta``, "less" tests ``estimand >=
    delta``, and "two-sided" tests equality.
    """
    if alternative == "greater":
        return estimand <= delta
    elif alternative == "less":
        return estimand >= delta
    elif alternative == "two-sided":
        return math.isclose(estimand, delta, abs_tol=1e-12)
    else:
        raise ValueError(f"Unrecognized alternative: {alternative!r}")


def claim_estimand(
    claim: Claim, regions: Mapping[str, Region], effects: EffectConfiguration
) -> float:
    """The true value of what a claim is about.

    An effect claim is about tau in its node; a heterogeneity claim about
    tau_right - tau_left across its split.
    """
    if claim.kind == "effect":
        return effects.average(regions[claim.node].cells)

    assert claim.left is not None and claim.right is not None  # Satisfy type-checker
    return effects.average(regions[claim.right].cells) - effects.average(
        regions[claim.left].cells
    )


@dataclass(frozen=True)
class Verdicts:
    """One procedure's decisions on one hierarchy, scored against the truth."""

    rejected: tuple[bool, ...]
    null_true: tuple[bool, ...]
    depths: tuple[int, ...]

    @property
    def familywise_error(self) -> bool:
        """Whether any true null was rejected."""
        return any(r and t for r, t in zip(self.rejected, self.null_true, strict=True))

    @property
    def true_claims(self) -> int:
        """Rejections of false nulls."""
        return sum(
            r and not t for r, t in zip(self.rejected, self.null_true, strict=True)
        )

    def true_claims_by_depth(self, max_depth: int) -> tuple[int, ...]:
        """True claims at each decision-tree depth, the root at zero."""
        counts = [0] * (max_depth + 1)
        for r, t, d in zip(self.rejected, self.null_true, self.depths, strict=True):
            if r and not t and d <= max_depth:
                counts[d] += 1

        return tuple(counts)


def score(
    claims: list[Claim],
    rejected: list[bool],
    regions: Mapping[str, Region],
    effects: EffectConfiguration,
) -> Verdicts:
    """Pair each decision with whether its null was true."""
    null_true = tuple(
        null_is_true(
            claim_estimand(claim, regions, effects), claim.delta, claim.alternative
        )
        for claim in claims
    )
    return Verdicts(
        rejected=tuple(rejected),
        null_true=null_true,
        depths=tuple(claim.depth for claim in claims),
    )


def build_hierarchy(
    tree: UpliftNode, procedure: str, alpha: float = ALPHA
) -> UpliftClaims:
    """The interweaved hierarchy as the given procedure configures it.

    Bonferroni and Hierarchical Bonferroni need only the adaptive
    hypotheses and their p-values; they share the trickle-down family.
    """
    if procedure == "Fixed hierarchy":
        return interweaved_hierarchy(
            tree, alpha, delta=DELTA, effect_stake=1.0, heterogeneity_stake=1.0
        )
    elif procedure == "Non-adaptive":
        return interweaved_hierarchy(
            tree,
            alpha,
            delta=DELTA,
            effect_stake=STAKE,
            heterogeneity_stake=STAKE,
            adaptive=False,
        )
    elif procedure in ("Bonferroni", "Hierarchical Bonferroni", "Trickle down"):
        return interweaved_hierarchy(
            tree, alpha, delta=DELTA, effect_stake=STAKE, heterogeneity_stake=STAKE
        )
    else:
        raise ValueError(f"Unrecognized procedure: {procedure!r}")


def apply_procedures(
    tree: UpliftNode,
    regions: Mapping[str, Region],
    effects: EffectConfiguration,
    alpha: float = ALPHA,
) -> dict[str, Verdicts]:
    """Run all five procedures of section 7.2 on one tree and score them."""
    adaptive = build_hierarchy(tree, "Trickle down", alpha).test()
    fixed = build_hierarchy(tree, "Fixed hierarchy", alpha).test()
    two_sided = build_hierarchy(tree, "Non-adaptive", alpha).test()

    decisions: dict[str, tuple[list[Claim], list[bool]]] = {
        "Bonferroni": (adaptive.claims, bonferroni_rejections(adaptive.claims, alpha)),
        "Hierarchical Bonferroni": (
            adaptive.claims,
            hierarchical_bonferroni_rejections(adaptive.claims, alpha),
        ),
        "Fixed hierarchy": (fixed.claims, [c.rejected for c in fixed.claims]),
        "Trickle down": (adaptive.claims, [c.rejected for c in adaptive.claims]),
        "Non-adaptive": (two_sided.claims, [c.rejected for c in two_sided.claims]),
    }
    return {
        procedure: score(claims, rejected, regions, effects)
        for procedure, (claims, rejected) in decisions.items()
    }


def fwer_replicate(
    seed: np.random.SeedSequence, n: int = 4_000
) -> dict[str, dict[str, bool]]:
    """One global-null population, tested on both partitions (section 7.2).

    Returns, for each partition and procedure, whether a familywise error
    occurred. Both partitions see the same population and the same split,
    so the comparison between them is paired.
    """
    rng = np.random.default_rng(seed)
    population = generate_population(rng, n, GLOBAL_NULL)
    train, evaluation = split_halves(rng, population)

    results: dict[str, dict[str, bool]] = {}
    for label, region in (
        ("Fixed partition", fixed_partition()),
        ("Fitted tree", fitted_partition(train)),
    ):
        tree = to_uplift_tree(region, train, evaluation)
        if tree is None:
            raise RuntimeError("The root of a population cannot be untestable.")

        regions = {r.name: r for r in region.walk()}
        verdicts = apply_procedures(tree, regions, GLOBAL_NULL)
        results[label] = {p: v.familywise_error for p, v in verdicts.items()}

    return results


def power_replicate(
    seed: np.random.SeedSequence,
    effects: EffectConfiguration,
    n: int = 4_000,
) -> dict[str, tuple[int, ...]]:
    """One population on the fixed partition (section 7.3).

    Returns, for each procedure, the true claims certified at the root,
    depth one and depth two.
    """
    rng = np.random.default_rng(seed)
    population = generate_population(rng, n, effects)
    train, evaluation = split_halves(rng, population)
    region = fixed_partition()
    tree = to_uplift_tree(region, train, evaluation)
    if tree is None:
        raise RuntimeError("The root of a population cannot be untestable.")

    regions = {r.name: r for r in region.walk()}
    verdicts = apply_procedures(tree, regions, effects)
    return {p: v.true_claims_by_depth(max_depth=2) for p, v in verdicts.items()}


@dataclass(frozen=True)
class WorkedExample:
    """The single run of section 7.1, with everything the docs report."""

    region: Region
    tree: UpliftNode
    claims: UpliftClaims
    effects: EffectConfiguration
    train: Sample
    evaluation: Sample

    def node_rows(self) -> list[tuple[str, int, float, float, float]]:
        """Name, depth, tau_train, tau_eval and true tau for every node."""
        nodes = {node.name: node for node in self.tree.walk()}
        rows = []
        for region in self.region.walk():
            node = nodes.get(region.name)
            if node is None:
                continue  # Dropped as untestable.

            rows.append(
                (
                    region.name,
                    len(region.conditions),
                    node.tau_train,
                    node.tau_hat,
                    self.effects.average(region.cells),
                )
            )

        return rows


def worked_example(seed: int, n: int = 10_000) -> WorkedExample:
    """Run section 7.1 once: fit, build the hierarchy, and test it."""
    rng = np.random.default_rng(seed)
    population = generate_population(rng, n, RUNNING_EXAMPLE)
    train, evaluation = split_halves(rng, population)
    region = fitted_partition(train)
    tree = to_uplift_tree(region, train, evaluation)
    if tree is None:
        raise RuntimeError("The root of a population cannot be untestable.")

    claims = interweaved_hierarchy(
        tree, ALPHA, delta=DELTA, effect_stake=STAKE, heterogeneity_stake=STAKE
    ).test()
    return WorkedExample(
        region=region,
        tree=tree,
        claims=claims,
        effects=RUNNING_EXAMPLE,
        train=train,
        evaluation=evaluation,
    )
